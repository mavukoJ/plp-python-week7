
# Week 7 Assignment - List Warmup

# My list of four favorite fruits
fruits = ["mango", "orange", "banana", "apple"]

# Print the first and last fruits
print("First fruit:", fruits[0])
print("Last fruit:", fruits[-1])

# Add another fruit to my list
fruits.append("watermelon")
print("After adding a fruit:", fruits)

# Remove one fruit
fruits.remove("orange")
print("After removing a fruit:", fruits)

# Count the fruits remaining
print("Number of fruits:", len(fruits))
